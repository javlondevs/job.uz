export const dict = { uz, ru, en };

// Tarjima olish: t("uz", "jobs.filters")
export function translate(lang, path, vars) {
  let val = dict[lang] || dict.uz;
  for (const key of String(path).split(".")) {
    if (val == null) break;
    val = val[key];
  }
  if (val == null) val = dict.uz;
  // fallback: oxirgi qismni qaytarish
  if (typeof val !== "string") return path.split(".").pop();
  if (vars) {
    return Object.entries(vars).reduce(
      (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
      val
    );
  }
  return val;
}

